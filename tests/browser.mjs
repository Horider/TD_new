// Optional local integration check. Uses a new, headless browser profile.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';

const require = createRequire(import.meta.url);
let playwright;
try { playwright = require('playwright'); }
catch { playwright = require(path.join(homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')); }
const executablePath = process.env.CHROME_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const browser = await playwright.chromium.launch({ headless:true, ...(executablePath ? {executablePath} : {}) });
await mkdir('test-results',{recursive:true});
const errors=[],failed=[];
try {
  const page = await browser.newPage({ viewport:{width:1440,height:960}, deviceScaleFactor:1 });
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400)failed.push(`${r.status()} ${r.url()}`);});
  await page.goto(process.env.GAME_URL || 'http://127.0.0.1:4173/');
  await page.locator('#loading-screen').waitFor({state:'hidden'});
  assert.equal(await page.title(),'Лесной рубеж');
  assert.equal(await page.locator('.pad-button').count(),9);
  await page.screenshot({path:'test-results/desktop-preparation.png',fullPage:true});
  await page.locator('[data-pad="0"]').click();
  await page.keyboard.press('KeyB');
  assert.equal(await page.locator('#gold').innerText(),'270');
  await page.locator('[data-pad="1"]').click();await page.keyboard.press('KeyB');
  await page.locator('[data-pad="0"]').click();await page.keyboard.press('KeyU');
  assert.equal(await page.locator('#tower-level').innerText(),'II');
  assert.equal(await page.locator('#gold').innerText(),'60');
  const menu=await page.locator('#tower-selector').boundingBox();
  await page.mouse.click(menu.x+menu.width*.2,menu.y+menu.height*.5);
  assert.equal(await page.locator('#gold').innerText(),'207');
  await page.locator('[data-pad="6"]').click();await page.keyboard.press('KeyB');
  assert.equal(await page.locator('[data-action="upgrade"]').getAttribute('aria-disabled'),'true');
  await page.locator('[data-pad="2"]').click();await page.keyboard.press('KeyB');
  await page.locator('#wave-button').click();
  await page.locator('#speed-button').click();
  await page.waitForFunction(()=>Number(document.querySelector('#kills-label').textContent.split(' ')[0])>0,null,{timeout:25000});
  await page.locator('#pause-button').click();
  const gold=await page.locator('#gold').innerText();
  assert.equal(await page.locator('#pause-screen').isVisible(),true);
  await page.locator('#maps-button').click();
  await page.locator('#maps-dialog .dialog-close').click();
  await page.locator('#pause-screen').waitFor({state:'visible'});
  assert.equal(await page.locator('#pause-screen').isVisible(),true);
  assert.equal(await page.locator('#gold').innerText(),gold);
  await page.locator('#resume-button').click();
  await page.keyboard.press('Escape');
  await page.keyboard.press('Space');
  await page.locator('#pause-screen').waitFor({state:'visible'});
  assert.equal(await page.locator('#pause-screen').isVisible(),true);
  await page.keyboard.press('Space');
  await page.locator('#pause-screen').waitFor({state:'hidden'});
  assert.equal(await page.locator('#pause-screen').isVisible(),false);
  await page.screenshot({path:'test-results/desktop-battle.png',fullPage:true});
  await page.locator('#maps-button').click();
  assert.equal(await page.locator('.map-card').count(),4);
  await page.screenshot({path:'test-results/locations.png',fullPage:true});
  await page.locator('[data-map="field"]').click();
  await page.locator('#loading-screen').waitFor({state:'hidden'});
  assert.equal(await page.locator('#map-title').innerText(),'Цветущие поля');
  assert.equal(await page.locator('.pad-button').count(),8);
  assert.equal(await page.locator('#gold').innerText(),'360');
  assert.equal(await page.locator('#wave').innerText(),'0');
  await page.locator('[data-pad="3"]').click();await page.keyboard.press('KeyB');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.screenshot({path:'test-results/mobile.png',fullPage:true});
  await page.locator('#restart-button').click();
  await page.locator('#restart-confirm').click();
  await page.locator('#loading-screen').waitFor({state:'hidden'});
  assert.equal(await page.locator('#gold').innerText(),'360');
  assert.equal(await page.locator('.pad-button.occupied').count(),0);
  await page.setViewportSize({width:1280,height:720});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollHeight<=window.innerHeight+1),true);
  await page.screenshot({path:'test-results/compact-desktop.png',fullPage:true});
  await page.setViewportSize({width:1440,height:960});
  await page.locator('#maps-button').click();await page.locator('[data-map="mountain_forest"]').click();
  await page.locator('#loading-screen').waitFor({state:'hidden'});
  assert.equal(await page.locator('#map-title').innerText(),'Каменный перевал');
  await page.locator('#maps-button').click();await page.locator('[data-map="forest_edge"]').click();
  await page.locator('#loading-screen').waitFor({state:'hidden'});
  assert.equal(await page.locator('#map-title').innerText(),'Солнечная опушка');
  assert.deepEqual(errors,[]);assert.deepEqual(failed,[]);
  console.log('PASS: assets, construction, upgrade, sale, combat, pause, speed, all four maps, restart, mobile layout. No browser or HTTP errors.');
} finally { await browser.close(); }
